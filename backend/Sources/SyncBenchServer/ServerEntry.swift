import Foundation
import Vapor

@main
enum SyncBenchMain {
    static func main() throws {
        let args = Array(CommandLine.arguments.dropFirst())
        if args.first == "compare" { try compare(args.dropFirst()); return }
        if args.first == "results" { try writeResults(args.dropFirst()); return }
        let env = try Environment.detect()
        let app = Application(env)
        defer { app.shutdown() }
        try configure(app)
        try app.run()
    }

    private static func compare(_ args: ArraySlice<String>) throws {
        let scenarios = try ScenarioCatalog.load()
        var rows = ["| Scenario | Synchronizer | Result | Lost updates | Duplicate effects | Retries | Failed assertions |", "|---|---|---|---:|---:|---:|---|"]
        var passedCounts = ["reference": 0, "naive": 0]
        var totalCounts = ["reference": 0, "naive": 0]
        for scenario in scenarios.values.sorted(by: { $0.id < $1.id }) {
            for mode in ["reference", "naive"] {
                var runner = ScenarioRunner(scenario: scenario, synchronizer: mode)
                let report = runner.run()
                let metrics = report.metrics
                let failures = report.assertions.filter { !$0.passed }.map { $0.name }.joined(separator: ", ")
                rows.append("| \(scenario.id) | \(mode) | \(report.status) | \(metrics.lostUpdates) | \(metrics.duplicateEffects) | \(metrics.retries) | \(failures.isEmpty ? "-" : failures) |")
                totalCounts[mode, default: 0] += 1
                if report.status == "passed" { passedCounts[mode, default: 0] += 1 }
            }
        }
        let summaries = ["reference", "naive"].map { "\n**\($0)**: \(passedCounts[$0] ?? 0)/\(totalCounts[$0] ?? 0) scenarios passed" }
        let output = rows.joined(separator: "\n") + "\n" + summaries.joined(separator: "\n") + "\n"
        if let index = args.firstIndex(of: "--write"), args.index(after: index) < args.endIndex {
            let path = URL(fileURLWithPath: String(args[args.index(after: index)]), relativeTo: URL(fileURLWithPath: FileManager.default.currentDirectoryPath + "/")).standardizedFileURL
            let header = "# Synchronizer comparison (generated)\n\nGenerated by `swift run syncbench-server compare`. These results describe SyncBench's virtual-clock model, not measurements on a real network.\n\n"
            try FileManager.default.createDirectory(at: path.deletingLastPathComponent(), withIntermediateDirectories: true)
            try (header + output).write(to: path, atomically: true, encoding: .utf8)
        }
        print(output, terminator: "")
    }

    private static func writeResults(_ args: ArraySlice<String>) throws {
        let scenarios = try ScenarioCatalog.load()
        let outputPath: String
        if let index = args.firstIndex(of: "--write"), args.index(after: index) < args.endIndex {
            outputPath = String(args[args.index(after: index)])
        } else { outputPath = "../results/result.md" }
        let encoder = JSONEncoder.sorted
        encoder.outputFormatting.insert(.prettyPrinted)
        let compactEncoder = JSONEncoder.sorted
        var lines = ["# SyncBench verification results", "", "Generated at \(ISO8601DateFormatter().string(from: Date())).", "",
                     "This report runs every checked-in scenario with both `reference` and `naive`, using the scenario's declared seed. Simulation delays use virtual time; wall-clock milliseconds only measure execution of this process.", "",
                     "## Metric definitions", "", "| Metric | Meaning |", "|---|---|",
                     "| Status | `passed` means all requested assertions passed; `failed` means one or more did not. |",
                     "| Events | Number of ordered timeline records in the run. |",
                     "| Retries | Additional attempts after a failed delivery attempt. |",
                     "| Lost updates | Fields whose final server value differs from their last accepted update value. |",
                     "| Duplicate effects | Operation IDs accepted more than once by the simulated server. |",
                     "| Failed assertions | Requested assertions that did not hold at the end of the run. |",
                     "| Simulated ms | Virtual elapsed time from injected delay, timeout, and retry backoff. |",
                     "| Wall ms | Process execution time; it varies with machine load and is not simulated network latency. |",
                     "| Fingerprint | First 16 hex characters of SHA-256 over the sorted-key encoded event timeline. |",
                     "", "## Suite summary", "", "| Scenario | Mode | Status | Events | Retries | Lost updates | Duplicate effects | Failed assertions | Simulated ms | Wall ms | Fingerprint |", "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
        var reports: [(Scenario, RunReport)] = []
        for scenario in scenarios.values.sorted(by: { $0.id < $1.id }) {
            for mode in ["reference", "naive"] {
                var runner = ScenarioRunner(scenario: scenario, synchronizer: mode)
                let report = runner.run()
                reports.append((scenario, report))
                let m = report.metrics
                lines.append("| \(scenario.id) | \(mode) | \(report.status) | \(m.events) | \(m.retries) | \(m.lostUpdates) | \(m.duplicateEffects) | \(m.assertionsFailed) | \(m.simulatedDurationMs) | \(String(format: "%.2f", m.wallMs)) | `\(report.fingerprint)` |")
            }
        }
        lines += ["", "## Detailed scenarios", ""]
        for scenario in scenarios.values.sorted(by: { $0.id < $1.id }) {
            lines += ["### \(scenario.name) (`\(scenario.id)`)" , "", scenario.description, "", "#### Complete scenario parameters", "", "```json", String(decoding: try encoder.encode(scenario), as: UTF8.self), "```", ""]
            for mode in ["reference", "naive"] {
                guard let report = reports.first(where: { $0.0.id == scenario.id && $0.1.synchronizer == mode })?.1 else { continue }
                lines += ["#### \(mode.capitalized) result", "", "| Parameter / metric | Value |", "|---|---:|"]
                lines += ["| Scenario ID | `\(report.scenarioId)` |", "| Synchronizer | `\(report.synchronizer)` |", "| Policy | `\(report.policy)` |", "| Seed | \(report.seed) |", "| Status | **\(report.status)** |", "| Event count | \(report.metrics.events) |", "| Retry count | \(report.metrics.retries) |", "| Lost updates | \(report.metrics.lostUpdates) |", "| Duplicate effects | \(report.metrics.duplicateEffects) |", "| Assertions total | \(report.metrics.assertionsTotal) |", "| Assertions failed | \(report.metrics.assertionsFailed) |", "| Simulated duration (ms) | \(report.metrics.simulatedDurationMs) |", "| Wall time (ms) | \(String(format: "%.2f", report.metrics.wallMs)) |", "| SHA-256 event fingerprint (first 16 hex) | `\(report.fingerprint)` |", "", "Final server state:", "", "```json", String(decoding: try encoder.encode(report.finalServerState), as: UTF8.self), "```", "", "Assertions:", "", "| Assertion | Passed | Expected | Actual | Message | Event sequences |", "|---|---:|---|---|---|---|"]
                for assertion in report.assertions {
                    let expected = String(decoding: try compactEncoder.encode(assertion.expected), as: UTF8.self).replacingOccurrences(of: "|", with: "\\|")
                    let actual = String(decoding: try compactEncoder.encode(assertion.actual), as: UTF8.self).replacingOccurrences(of: "|", with: "\\|")
                    lines.append("| `\(assertion.name)` | \(assertion.passed ? "yes" : "no") | `\(expected)` | `\(actual)` | \(assertion.message.replacingOccurrences(of: "|", with: "\\|")) | \(assertion.eventSeqs.map(String.init).joined(separator: ", ")) |")
                }
                lines += ["", "Event timeline:", "", "| Seq | Virtual ms | Actor | Event | Detail |", "|---:|---:|---|---|---|"]
                for event in report.events {
                    let detail = String(decoding: try compactEncoder.encode(event.detail), as: UTF8.self).replacingOccurrences(of: "|", with: "\\|")
                    lines.append("| \(event.seq) | \(event.tMs) | \(event.actor) | `\(event.type)` | `\(detail)` |")
                }
                lines.append("")
            }
        }
        let url = URL(fileURLWithPath: outputPath, relativeTo: URL(fileURLWithPath: FileManager.default.currentDirectoryPath + "/")).standardizedFileURL
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try (lines.joined(separator: "\n") + "\n").write(to: url, atomically: true, encoding: .utf8)
        print("Wrote detailed scenario results to \(url.path)")
    }
}
