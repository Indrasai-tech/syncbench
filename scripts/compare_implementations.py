"""Run every scenario against both synchronizers and print/write a comparison table.

Usage:  python scripts/compare_implementations.py [--write docs/comparison-results.md]
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.engine.loader import load_scenarios  # noqa: E402
from app.engine.runner import run_scenario  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", help="write markdown table to this file")
    args = parser.parse_args()
    scenarios = load_scenarios()
    rows = ["| Scenario | Synchronizer | Result | Lost updates | Duplicate effects | Retries | Failed assertions |",
            "|---|---|---|---|---|---|---|"]
    totals = {"reference": [0, 0], "naive": [0, 0]}
    for sid, sc in scenarios.items():
        for mode in ("reference", "naive"):
            r = run_scenario(sc, mode)
            m = r["metrics"]
            failed = ", ".join(a["name"] for a in r["assertions"] if not a["passed"]) or "-"
            rows.append(f"| {sid} | {mode} | {r['status']} | {m['lost_updates']} | "
                        f"{m['duplicate_effects']} | {m['retries']} | {failed} |")
            totals[mode][0] += r["status"] == "passed"
            totals[mode][1] += 1
    summary = [f"\n**{mode}**: {p}/{n} scenarios passed" for mode, (p, n) in totals.items()]
    out = "\n".join(rows) + "\n" + "\n".join(summary) + "\n"
    print(out)
    if args.write:
        Path(args.write).write_text(
            "# Synchronizer comparison (generated)\n\nGenerated by `scripts/compare_implementations.py`. "
            "These are results from SyncBench's own virtual-clock simulation, not real network measurements.\n\n"
            + out, encoding="utf-8")


if __name__ == "__main__":
    main()
